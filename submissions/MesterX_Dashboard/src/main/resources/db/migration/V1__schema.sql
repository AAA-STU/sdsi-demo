-- MesterX Dashboard schema. Written in portable SQL that runs on PostgreSQL and H2 (PostgreSQL mode).

CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(255) NOT NULL UNIQUE,
    display_name      VARCHAR(255) NOT NULL,
    password_hash     VARCHAR(255),
    role              VARCHAR(32)  NOT NULL,
    status            VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    jira_account_id   VARCHAR(128),
    last_seen_at      TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE projects (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key       VARCHAR(32)  NOT NULL UNIQUE,
    name              VARCHAR(255) NOT NULL,
    jira_project_key  VARCHAR(32),
    budget_usd        NUMERIC(14, 2),
    alert_pct         INT          NOT NULL DEFAULT 80,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE project_members (
    project_id        BIGINT NOT NULL REFERENCES projects (id),
    user_id           BIGINT NOT NULL REFERENCES users (id),
    role_in_project   VARCHAR(16) NOT NULL,
    PRIMARY KEY (project_id, user_id)
);

CREATE TABLE llm_models (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(128) NOT NULL UNIQUE,
    provider          VARCHAR(64)  NOT NULL,
    tier              VARCHAR(16)  NOT NULL,
    enabled           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE model_prices (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id          BIGINT NOT NULL REFERENCES llm_models (id),
    input_per_1k      NUMERIC(12, 6) NOT NULL,
    output_per_1k     NUMERIC(12, 6) NOT NULL,
    valid_from        TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_to          TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_model_prices_model ON model_prices (model_id, valid_from);

CREATE TABLE routing_configs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope             VARCHAR(16) NOT NULL,          -- GLOBAL | PROJECT | USER
    project_id        BIGINT REFERENCES projects (id),
    user_id           BIGINT REFERENCES users (id),
    worker_model_id   BIGINT NOT NULL REFERENCES llm_models (id),
    expert_model_id   BIGINT NOT NULL REFERENCES llm_models (id),
    version           INT NOT NULL DEFAULT 1,
    updated_by        BIGINT REFERENCES users (id),
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX uq_routing_scope ON routing_configs (scope, project_id, user_id);

CREATE TABLE api_keys (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES users (id),
    label             VARCHAR(128) NOT NULL,
    key_prefix        VARCHAR(12)  NOT NULL,
    key_hash          VARCHAR(128) NOT NULL UNIQUE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at        TIMESTAMP WITH TIME ZONE,
    last_used_at      TIMESTAMP WITH TIME ZONE
);

CREATE TABLE usage_events (
    event_id          VARCHAR(64) PRIMARY KEY,
    ts                TIMESTAMP WITH TIME ZONE NOT NULL,
    day               DATE   NOT NULL,
    user_id           BIGINT NOT NULL REFERENCES users (id),
    project_id        BIGINT NOT NULL REFERENCES projects (id),
    worker_model_id   BIGINT REFERENCES llm_models (id),
    expert_model_id   BIGINT REFERENCES llm_models (id),
    worker_in         INT NOT NULL DEFAULT 0,
    worker_out        INT NOT NULL DEFAULT 0,
    expert_in         INT NOT NULL DEFAULT 0,
    expert_out        INT NOT NULL DEFAULT 0,
    worker_latency_ms INT NOT NULL DEFAULT 0,
    expert_latency_ms INT NOT NULL DEFAULT 0,
    worker_cost_usd   NUMERIC(14, 6) NOT NULL DEFAULT 0,
    expert_cost_usd   NUMERIC(14, 6) NOT NULL DEFAULT 0,
    baseline_cost_usd NUMERIC(14, 6) NOT NULL DEFAULT 0,
    savings_usd       NUMERIC(14, 6) NOT NULL DEFAULT 0,
    jira_key          VARCHAR(32),
    outcome           VARCHAR(16) NOT NULL,
    plugin_version    VARCHAR(32)
);
CREATE INDEX idx_usage_events_project_day ON usage_events (project_id, day);
CREATE INDEX idx_usage_events_user_day ON usage_events (user_id, day);
CREATE INDEX idx_usage_events_day ON usage_events (day);

CREATE TABLE jira_issues (
    issue_key         VARCHAR(32) PRIMARY KEY,
    project_id        BIGINT REFERENCES projects (id),
    assignee_user_id  BIGINT REFERENCES users (id),
    assignee_account  VARCHAR(128),
    summary           VARCHAR(512),
    status            VARCHAR(64),
    status_category   VARCHAR(16),
    issue_type        VARCHAR(32),
    created_at        TIMESTAMP WITH TIME ZONE,
    updated_at        TIMESTAMP WITH TIME ZONE,
    resolved_at       TIMESTAMP WITH TIME ZONE,
    synced_at         TIMESTAMP WITH TIME ZONE,
    url               VARCHAR(512)
);
CREATE INDEX idx_jira_assignee ON jira_issues (assignee_user_id, project_id);

CREATE TABLE audit_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts                TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id          BIGINT REFERENCES users (id),
    actor_email       VARCHAR(255),
    action            VARCHAR(64)  NOT NULL,
    entity            VARCHAR(64)  NOT NULL,
    entity_id         VARCHAR(64),
    before_json       VARCHAR(10000),
    after_json        VARCHAR(10000)
);
CREATE INDEX idx_audit_ts ON audit_log (ts);
